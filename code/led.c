#include "led.h"

/************************ 初始化 ************************/
void LED_Init(void)
{
    LED_OUT;      // P00 推挽输出
    LED_PIN = 0;  // 默认熄灭
}

/************************ 点亮 ************************/
void LED_On(void)
{
    LED_PIN = 1;
}

/************************ 熄灭 ************************/
void LED_Off(void)
{
    LED_PIN = 0;
}

/************************ 设置 ************************/
void LED_Set(u8 val)
{
    LED_PIN = (val != 0) ? 1 : 0;
}

/************************ 翻转 ************************/
void LED_Toggle(void)
{
    LED_PIN = !LED_PIN;  // 亮 -> 灭, 灭 -> 亮
}
